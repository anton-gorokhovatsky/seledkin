import { readFileSync } from "node:fs";
import { inventory } from "../assets/catalog-data.js";

export const olegSources = JSON.parse(readFileSync(new URL("../content/oleg-sources.json", import.meta.url), "utf8"));
const products = new Set(inventory.flatMap(category => category.items.map(product => product.id)));
const chapters = new Set();

for (const audio of olegSources.audio) {
  if (!Number.isInteger(audio.durationSeconds) || audio.durationSeconds <= 0 || !audio.summary) {
    throw new Error(`Missing reviewed audio content: ${audio.id}`);
  }
  for (const chapter of audio.chapters) {
    if (chapters.has(chapter.id) || !chapter.label || !chapter.note
      || !Number.isInteger(chapter.start) || !Number.isInteger(chapter.end)
      || chapter.start < 0 || chapter.end <= chapter.start || chapter.end > audio.durationSeconds
      || chapter.products.some(id => !products.has(id))) {
      throw new Error(`Invalid reviewed audio chapter: ${chapter.id}`);
    }
    chapters.add(chapter.id);
    if (chapter.catalogQuote && (!Number.isInteger(chapter.quoteStart)
      || chapter.quoteStart < chapter.start || chapter.quoteStart >= chapter.end)) {
      throw new Error(`Invalid catalog quotation time: ${chapter.id}`);
    }
  }
  const linkedProducts = [...new Set(audio.chapters.flatMap(chapter => chapter.products))];
  if (JSON.stringify(linkedProducts) !== JSON.stringify(audio.products)) {
    throw new Error(`Audio products differ from reviewed chapters: ${audio.id}`);
  }
}

export const audioTime = seconds => `${Math.floor(seconds / 60)}:${String(seconds % 60).padStart(2, "0")}`;

// This fragment format is generated by SoundCloud's own Share > at control.
export const audioFragmentHref = (audio, chapter) => `${audio.url}#t=${encodeURIComponent(audioTime(chapter.start))}`;
